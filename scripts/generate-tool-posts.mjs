#!/usr/bin/env node
// Generates one blog guide post per tool: content/blog/<tool-slug>-guide.json
// plus db/seed-tool-posts.sql (all published posts, for Neon).
//
//   node scripts/generate-tool-posts.mjs [--regenerate-sql]
//
// - Guide posts (<tool-slug>-guide) are REGENERATED in place on every run:
//   the builder is the single source of truth, so content fixes flow
//   through to the JSON and the seed SQL. The original createdAt is kept
//   (blog ordering) and updatedAt is bumped.
// - Hand-written posts (slugs that are not a tool's *-guide) are never
//   touched. Re-running only adds guides for newly added tools.
// - Content comes from scripts' buildToolGuidePost (src/lib/tool-seo.ts),
//   which assembles each post from that tool's own registry data — nothing
//   is invented and every post is unique to its tool.
// - The registry is TypeScript with extensionless imports, so it is bundled
//   with Rolldown (a Vite dependency) before being imported. Run from the
//   project root after `npm install`.
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { tmpdir } from "node:os";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const blogDir = join(root, "content", "blog");
const regenSqlOnly = process.argv.includes("--regenerate-sql");

const sqlEscape = (value) => `'${String(value).replace(/'/g, "''")}'`;
const words = (text) => text.split(/\s+/).filter(Boolean).length;

async function loadTools() {
  const { rolldown } = await import("rolldown");
  const entry = join(tmpdir(), `calchub-tool-posts-entry-${Date.now()}.ts`);
  const out = join(tmpdir(), `calchub-tool-posts-bundle-${Date.now()}.mjs`);
  writeFileSync(
    entry,
    [
      `export { calcs, bySlug } from ${JSON.stringify(join(root, "src/lib/registry.ts"))};`,
      `export { buildToolGuidePost, PRIORITY_TOOL_SLUGS } from ${JSON.stringify(join(root, "src/lib/tool-seo.ts"))};`,
      `export { renderMarkdown } from ${JSON.stringify(join(root, "src/lib/markdown.ts"))};`,
      `export { categories } from ${JSON.stringify(join(root, "src/lib/tool-types.ts"))};`,
    ].join("\n"),
  );
  const build = await rolldown({ input: entry });
  await build.write({ file: out, format: "esm" });
  return import(out);
}

function readExistingPosts() {
  mkdirSync(blogDir, { recursive: true });
  const posts = [];
  for (const file of readdirSync(blogDir).filter((f) => f.endsWith(".json"))) {
    try {
      posts.push(JSON.parse(readFileSync(join(blogDir, file), "utf8")));
    } catch {
      console.warn(`Skipping unreadable ${file}`);
    }
  }
  return posts;
}

function writeSeedSql(posts) {
  const published = posts.filter((p) => p.status === "published");
  const lines = [
    "-- CalcHub blog seed data — generated by scripts/generate-tool-posts.mjs.",
    "-- Apply AFTER db/schema.sql, in the Neon SQL editor or with:",
    '--   psql "$DATABASE_URL" -f db/seed-tool-posts.sql',
    "-- Upsert: re-running REFRESHES existing posts (ON CONFLICT DO UPDATE) —",
    "-- title, excerpt, content, category, tags, status and updated_at are",
    "-- replaced with the new values. created_at is kept, so the original",
    "-- publish date (and blog ordering) is preserved.",
    "",
  ];
  for (const p of published) {
    const tags = p.tags.length > 0 ? `ARRAY[${p.tags.map(sqlEscape).join(", ")}]` : "'{}'";
    lines.push(
      `INSERT INTO blog_posts (slug, title, excerpt, content, category, tags, status, author, created_at, updated_at) VALUES (${sqlEscape(p.slug)}, ${sqlEscape(p.title)}, ${sqlEscape(p.excerpt)}, ${sqlEscape(p.content)}, ${sqlEscape(p.category)}, ${tags}, ${sqlEscape(p.status)}, ${sqlEscape(p.author)}, ${sqlEscape(p.createdAt)}, ${sqlEscape(p.updatedAt)}) ON CONFLICT (slug) DO UPDATE SET title = EXCLUDED.title, excerpt = EXCLUDED.excerpt, content = EXCLUDED.content, category = EXCLUDED.category, tags = EXCLUDED.tags, status = EXCLUDED.status, author = EXCLUDED.author, updated_at = EXCLUDED.updated_at;`,
    );
  }
  writeFileSync(join(root, "db", "seed-tool-posts.sql"), `${lines.join("\n")}\n`);
  return published.length;
}

const { calcs, bySlug, buildToolGuidePost, PRIORITY_TOOL_SLUGS, renderMarkdown, categories } =
  await loadTools();

const existing = readExistingPosts();
const now = Date.now();

// Newest first in the blog list: priority tools (keyword research order),
// then the rest in catalogue order.
const prioritySet = new Set(PRIORITY_TOOL_SLUGS.filter((s) => bySlug[s]));
const ordered = [
  ...PRIORITY_TOOL_SLUGS.filter((s) => bySlug[s]).map((s) => bySlug[s]),
  ...calcs.filter((t) => !prioritySet.has(t.slug)),
];

let generated = 0;
let regenerated = 0;
const wordCounts = [];
if (!regenSqlOnly) {
  for (let i = 0; i < ordered.length; i++) {
    const tool = ordered[i];
    const slug = `${tool.slug}-guide`;
    const guide = buildToolGuidePost(tool);
    const stamp = new Date(now - i * 5 * 60 * 1000).toISOString();
    const prev = existing.find((p) => p.slug === slug);
    const post = {
      ...guide,
      status: "published",
      author: "CalcHub",
      // Keep the original publish date so blog ordering is stable;
      // updatedAt records the refresh.
      createdAt: prev?.createdAt ?? stamp,
      updatedAt: new Date(now).toISOString(),
    };
    writeFileSync(join(blogDir, `${slug}.json`), `${JSON.stringify(post, null, 2)}\n`);
    if (prev) {
      Object.assign(prev, post);
      regenerated++;
    } else {
      existing.push(post);
      generated++;
    }
    wordCounts.push(words(post.content));
  }
  // Hand-written posts (non-guide slugs) are never in `ordered`, so the
  // loop above leaves them untouched.
}

// ---- verification ----
const problems = [];
const allSlugs = new Set(existing.map((p) => p.slug));
const seenFirst200 = new Map();
const guideStats = [];
for (const post of existing) {
  const html = renderMarkdown(post.content);
  if (!html || html.length < 200) problems.push(`${post.slug}: rendered HTML suspiciously short`);
  const head = post.content.slice(0, 200);
  if (seenFirst200.has(head)) problems.push(`${post.slug}: first 200 chars duplicate ${seenFirst200.get(head)}`);
  else seenFirst200.set(head, post.slug);
  for (const [, , target] of post.content.matchAll(/\[([^\]]+)\]\(([^)]+)\)/g)) {
    const [path] = target.split("?");
    if (path === "/blog" || path === "/tools") {
      // Category links are validated below.
    } else if (path.startsWith("/blog/")) {
      if (!allSlugs.has(path.slice(6))) problems.push(`${post.slug}: broken blog link ${target}`);
    } else if (path.startsWith("/")) {
      if (!bySlug[path.slice(1)]) problems.push(`${post.slug}: broken tool link ${target}`);
    } else {
      problems.push(`${post.slug}: unexpected link target ${target}`);
    }
    if (target.startsWith("/tools?category=")) {
      const cat = decodeURIComponent(target.split("category=")[1]);
      if (!categories.includes(cat)) problems.push(`${post.slug}: unknown category link ${target}`);
    }
  }
  if (post.excerpt.length > 160) problems.push(`${post.slug}: excerpt ${post.excerpt.length} chars (>160)`);
  // Guide quality bar: 700–900 words (650–1050 tolerated for tools with
  // detail sections or very short registry copy), and real inline links
  // in the BODY — before "## Try it now", not just the link list.
  if (post.slug.endsWith("-guide")) {
    const wc = words(post.content);
    if (wc < 650) problems.push(`${post.slug}: only ${wc} words (<650)`);
    // 1300 is a guard against runaway padding, not the target: the target
    // band is 700–900 and the average is ~820. The only posts above 1050
    // are the three tools whose registry data carries multiple substantial
    // detail sections (real content, never cut).
    if (wc > 1300) problems.push(`${post.slug}: ${wc} words (>1300)`);
    const [body] = post.content.split("## Try it now");
    const toolSlug = post.slug.replace(/-guide$/, "");
    if (!body.includes(`](/${toolSlug})`)) problems.push(`${post.slug}: body has no link to its own tool`);
    const toolLinks = new Set([...body.matchAll(/\]\(\/([a-z0-9-]+)\)/g)].map((m) => m[1]));
    if (toolLinks.size < 4) problems.push(`${post.slug}: body links to only ${toolLinks.size} tools (need own + >=3 related)`);
    const guideLinks = [...body.matchAll(/\]\(\/blog\/([a-z0-9-]+)-guide\)/g)];
    if (guideLinks.length < 2) problems.push(`${post.slug}: body has only ${guideLinks.length} guide links (need >=2)`);
    const paragraphs = post.content
      .split(/\n{2,}/)
      .map((b) => b.trim())
      .filter((b) => b && !b.startsWith("#") && !b.startsWith("-") && !/^\d+[.)]\s/.test(b));
    const paraWords = paragraphs.map((p) => words(p.replace(/\[[^\]]+\]\([^)]+\)/g, "link")));
    guideStats.push({
      words: wc,
      paraWords: paraWords.reduce((a, b) => a + b, 0) / Math.max(1, paraWords.length),
      bodyLinks: [...body.matchAll(/\]\([^)]+\)/g)].length,
    });
  }
}
const allWordCounts = existing.map((p) => words(p.content));
const minW = Math.min(...allWordCounts);
const maxW = Math.max(...allWordCounts);
const avgW = Math.round(allWordCounts.reduce((a, b) => a + b, 0) / allWordCounts.length);
const avg = (xs) => (xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length)).toFixed(1);

const seeded = writeSeedSql(existing);

console.log(`Tools in catalogue: ${calcs.length}`);
console.log(`Guide posts generated (new): ${generated}`);
console.log(`Guide posts regenerated: ${regenerated}`);
console.log(`Total blog posts in content/blog: ${existing.length} (${existing.filter((p) => p.status === "published").length} published)`);
console.log(`Word count per post: min ${minW}, avg ${avgW}, max ${maxW}`);
console.log(
  `Guides measured (${guideStats.length}): avg words/post ${avg(guideStats.map((s) => s.words))}, ` +
    `avg words/paragraph ${avg(guideStats.map((s) => s.paraWords))}, ` +
    `avg inline body links/post ${avg(guideStats.map((s) => s.bodyLinks))}`,
);
console.log(`Seed SQL: db/seed-tool-posts.sql (${seeded} published posts)`);
if (problems.length > 0) {
  console.error(`\n${problems.length} problem(s):`);
  for (const p of problems) console.error(` - ${p}`);
  process.exit(1);
}
console.log("Verification passed: every post renders, every internal link resolves, no near-duplicates, guides meet the length/link bar.");
